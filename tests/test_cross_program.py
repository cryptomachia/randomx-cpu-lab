"""rxlab.spec's program generator and decoder against build/progdump (tools/progdump.cpp).

progdump replays randomx_calculate_hash with the C library's own generator,
bytecode compiler and interpreter, and dumps every program's raw bytes, static
features and dynamic counters. The spec code must generate the same programs,
decode them into the same features and (slow) execute the same instruction
stream. The tests skip when progdump cannot be built.
"""
import collections
import struct
import subprocess

import pytest

from rxlab import binding
from rxlab.analysis import programs as P
from rxlab.spec import aes, params, program
from rxlab.spec.hasher import CDatasetItemSource, hash512, randomx_hash
from rxlab.spec.light import VECTORS

KEY = b"test key 000"
# Vectors 1a-1c, then the vector-1e Monero blob under a few nonces.
INPUTS = [v[2] for v in VECTORS if v[1] == KEY] + [P.blob_with_nonce(n) for n in (0, 1, 2, 3, 2**32 - 1)]
LEVEL = {program.L1_MASK: "l1", program.L2_MASK: "l2", program.L3_MASK: "l3"}
MEMORY_READS = {"IADD_M", "ISUB_M", "IMUL_M", "IMULH_M", "ISMULH_M", "IXOR_M", "FADD_M", "FSUB_M",
                "FDIV_M"}
REGISTER_OR_IMMEDIATE = {"ISUB_R", "IMUL_R", "IXOR_R", "IROR_R", "IROL_R"}
COLUMNS = ["n_" + name for name, _ in params.FREQUENCIES] + [
    "nop_eff", "rd_l1", "rd_l2", "rd_l3", "rd_fp", "wr_l1", "wr_l2", "wr_l3", "imm_src",
    "cbr_body", "cbr_body_max"]


@pytest.fixture(scope="module")
def dumps():
    """Light-mode progdump tables (raw programs included) for INPUTS, v1 and v2."""
    try:
        P.ensure_progdump()
    except (OSError, subprocess.CalledProcessError) as exc:
        pytest.skip("progdump cannot be built: %s" % exc)
    return {v2: P.dump(v2, inputs=INPUTS, key=KEY, light=True, threads=2,
                       raw_limit=len(INPUTS), cache=False) for v2 in (False, True)}


@pytest.fixture(scope="module")
def first_seeds():
    """The seed of program 0 for each input: AesGenerator1R's state after the scratchpad fill."""
    seeds = []
    for data in INPUTS:
        gen = aes.AesGenerator1R(hash512(data))
        gen.generate(params.SCRATCHPAD_L3)
        seeds.append(gen.state)
    return seeds


def rows(table):
    return {(int(i), int(p)): row for row, (i, p) in enumerate(zip(table["input"], table["prog"]))}


def raw_bytes(prog):
    """A Program back to the 128 + 8 * size bytes it was parsed from."""
    return struct.pack("<16Q", *prog.entropy) + b"".join(struct.pack("<BBBBI", *i)
                                                         for i in prog.instructions)


def fnv1a(data):
    h = 0xCBF29CE484222325
    for byte in data:
        h = ((h ^ byte) * 0x100000001B3) & params.MASK64
    return h


def spec_features(prog):
    """progdump's decoder-dependent static columns, from rxlab.spec's decoded Ops."""
    f = dict.fromkeys(COLUMNS, 0)
    for pc, (instr, op) in enumerate(zip(prog.instructions, prog.ops)):
        f["n_" + instr.name] += 1
        if op.kind == "NOP":
            f["nop_eff"] += 1
        elif op.kind in MEMORY_READS:
            f["rd_" + LEVEL[op.mask]] += 1
            f["rd_fp"] += op.kind.startswith("F")
        elif op.kind == "ISTORE":
            f["wr_" + LEVEL[op.mask]] += 1
        elif op.kind in REGISTER_OR_IMMEDIATE:
            f["imm_src"] += op.src == program.SRC_IMM
        elif op.kind == "CBRANCH":
            f["cbr_body"] += pc - op.target  # re-executes target + 1 .. pc
            f["cbr_body_max"] = max(f["cbr_body_max"], pc - op.target)
    return f


def test_progdump_anchors_on_the_official_hashes(dumps):
    for v2, table in dumps.items():
        at = rows(table)
        for i, (_, key, data, h1, h2) in enumerate(v for v in VECTORS if v[1] == KEY):
            assert INPUTS[i] == data
            assert table["hash"][at[i, 7]] == (h2 if v2 else h1)


@pytest.mark.parametrize("v2", [False, True], ids=["v1", "v2"])
def test_first_programs_match(dumps, first_seeds, v2):
    """Program 0 of every input, generated by rxlab.spec, is byte-identical to the library's."""
    table = dumps[v2]
    at = rows(table)
    for i, seed in enumerate(first_seeds):
        raw = raw_bytes(program.generate(seed, v2))
        assert raw.hex() == table["raw"][at[i, 0]], "input %d" % i
        assert "%016x" % fnv1a(raw) == table["fingerprint"][at[i, 0]]


@pytest.mark.parametrize("v2", [False, True], ids=["v1", "v2"])
def test_decoder_matches_library_bytecode(dumps, v2):
    """All 8 programs of every input: rxlab.spec's decoding gives the library's features
    (effective NOPs, scratchpad levels, immediate sources, CBRANCH targets)."""
    table = dumps[v2]
    assert len(table["raw"]) == params.PROGRAM_COUNT * len(INPUTS)
    for row, raw in enumerate(table["raw"]):
        prog = program.from_bytes(bytes.fromhex(raw), v2)
        assert raw_bytes(prog).hex() == raw
        assert len(prog.ops) == table["size"][row]
        assert spec_features(prog) == {c: int(table[c][row]) for c in COLUMNS}, "row %d" % row


@pytest.mark.slow
@pytest.mark.skipif(not binding.library_path().exists(), reason="RandomX library missing")
@pytest.mark.parametrize("v2", [False, True], ids=["v1", "v2"])
def test_whole_hash_executes_like_the_library(dumps, first_seeds, v2):
    """Vector 1a through the spec VM (C Dataset items): all 8 programs are byte-identical
    to progdump's and execute the same numbers of instructions, taken branches, CFROUNDs
    and rounding-mode changes as the C interpreter."""
    table = dumps[v2]
    at = rows(table)
    stats = collections.Counter()
    snapshots, seeds = [], [first_seeds[0]]

    def observer(index, register_file, machine):
        snapshots.append(collections.Counter(stats))
        seeds.append(hash512(register_file))

    with CDatasetItemSource(KEY, lazy=True) as items:
        digest = randomx_hash(INPUTS[0], items, v2, observer=observer, stats=stats)
    assert digest.hex() == table["hash"][at[0, 7]]
    previous = collections.Counter()
    for p, counts in enumerate(snapshots):
        row = at[0, p]
        assert raw_bytes(program.generate(seeds[p], v2)).hex() == table["raw"][row]
        delta = counts - previous
        previous = counts
        executed = sum(n for k, n in delta.items() if k not in ("CBRANCH taken", "CFROUND changed"))
        got = {"executed": executed, "taken": delta["CBRANCH taken"], "cbr_exec": delta["CBRANCH"],
               "cfround_exec": delta["CFROUND"], "fprc_changes": delta["CFROUND changed"]}
        assert got == {c: int(table[c][row]) for c in got}, "program %d" % p
